#!/usr/bin/env python3
"""Generate SCAPVAL's OVAL 5.12.3 Schematron from a pinned OVAL checkout."""

import argparse
from copy import deepcopy
from pathlib import Path
import re
import subprocess
import sys

from lxml import etree


SCH = "http://purl.oclc.org/dsdl/schematron"
REPOSITORY = "https://github.com/OVAL-Community/OVAL"
SETS = {
    "definitions": "*-definitions-schema.xsd",
    "results": "oval-results-schema.xsd",
    "system-characteristics": "*-system-characteristics-schema.xsd",
}


def git(repo, *args):
    return subprocess.check_output(
        ["git", "--no-optional-locks", "-C", str(repo), *args], text=True
    ).strip()


def check_checkout(repo, expected_commit):
    if not re.fullmatch(r"[0-9a-f]{40}", expected_commit):
        raise ValueError("expected commit must be a full lowercase commit hash")
    actual = git(repo, "rev-parse", "HEAD")
    if actual != expected_commit:
        raise ValueError(f"OVAL checkout is at {actual}, expected {expected_commit}")
    if git(repo, "status", "--porcelain", "--untracked-files=all"):
        raise ValueError("OVAL checkout is dirty")


def canonical(element):
    return etree.tostring(element, method="c14n", with_comments=True)


def counts(schema):
    return tuple(len(schema.findall(f".//{{{SCH}}}{name}"))
                 for name in ("pattern", "rule", "assert", "report"))


def generate(repo, commit, name, glob, transform):
    inputs = sorted((repo / "oval-schemas").glob(glob))
    if not inputs:
        raise ValueError(f"no schemas found for {name}: {glob}")
    schema = etree.Element(f"{{{SCH}}}schema", nsmap={"sch": SCH})
    schema.addprevious(etree.Comment(
        f" Generated by tools/generate_oval_schematron.py from {REPOSITORY} "
        f"commit {commit}. "
    ))
    namespaces = {}
    patterns = set()
    pattern_ids = {}
    diagnostics = {}
    phases = {}
    diagnostic_container = etree.Element(f"{{{SCH}}}diagnostics")
    for path in inputs:
        # Real file paths provide the base URI required by document() in the XSLT.
        extracted = transform(etree.parse(str(path))).getroot()
        for child in extracted:
            if child.tag == f"{{{SCH}}}title":
                if schema.find(f"{{{SCH}}}title") is None:
                    schema.append(deepcopy(child))
            elif child.tag == f"{{{SCH}}}ns":
                prefix, uri = child.get("prefix"), child.get("uri")
                if prefix in namespaces and namespaces[prefix] != uri:
                    raise ValueError(f"namespace conflict for {prefix}: {path}")
                if prefix not in namespaces:
                    namespaces[prefix] = uri
                    schema.append(deepcopy(child))
            elif child.tag == f"{{{SCH}}}pattern":
                body = canonical(child)
                pattern_id = child.get("id")
                if pattern_id:
                    if pattern_id in pattern_ids and pattern_ids[pattern_id] != body:
                        raise ValueError(f"different pattern bodies share id {pattern_id}: {path}")
                    pattern_ids[pattern_id] = body
                if body not in patterns:
                    patterns.add(body)
                    schema.append(deepcopy(child))
            elif child.tag == f"{{{SCH}}}phase":
                key, body = child.get("id"), canonical(child)
                if key in phases and phases[key] != body:
                    raise ValueError(f"conflicting phase {key}: {path}")
                if key not in phases:
                    phases[key] = body
                    schema.append(deepcopy(child))
            elif child.tag == f"{{{SCH}}}diagnostics":
                for diagnostic in child:
                    key, body = diagnostic.get("id"), canonical(diagnostic)
                    if key in diagnostics and diagnostics[key] != body:
                        raise ValueError(f"conflicting diagnostic {key}: {path}")
                    if key not in diagnostics:
                        diagnostics[key] = body
                        diagnostic_container.append(deepcopy(diagnostic))
            else:
                raise ValueError(f"unexpected extracted element {child.tag}: {path}")

    before = counts(schema)
    print(f"{name} ({len(inputs)} XSDs), before dropping "
          f"oval_schema_version_core_matches_platforms: "
          f"{before[0]} patterns, {before[1]} rules, "
          f"{before[2]} asserts, {before[3]} reports")
    for pattern in schema.findall(f"{{{SCH}}}pattern"):
        if pattern.get("id") == "oval_schema_version_core_matches_platforms":
            schema.remove(pattern)
    if name == "results":
        for assertion in schema.findall(f".//{{{SCH}}}assert"):
            assertion.set("test", assertion.get("test").replace(
                "/oval-res:oval_results", "ancestor-or-self::oval-res:oval_results"
            ))
    if len(diagnostic_container):
        schema.append(diagnostic_container)
    # sch:ns declarations must precede patterns in the merged schema.
    order = {"title": 0, "ns": 1, "phase": 2, "pattern": 3, "diagnostics": 4}
    schema[:] = sorted(schema, key=lambda child: order[etree.QName(child).localname])
    after = counts(schema)
    print(f"{name}, generated: {after[0]} patterns, {after[1]} rules, "
          f"{after[2]} asserts, {after[3]} reports")
    return etree.tostring(schema.getroottree(), encoding="UTF-8",
                          xml_declaration=True, pretty_print=True).replace(b"\r\n", b"\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("oval_repo", type=Path)
    parser.add_argument("expected_commit")
    args = parser.parse_args()
    repo = args.oval_repo.expanduser().resolve()
    check_checkout(repo, args.expected_commit)
    transform = etree.XSLT(etree.parse(str(repo / "tools" / "ExtractSchFromXSD.xsl")))
    outputs = {
        name: generate(repo, args.expected_commit, name, glob, transform)
        for name, glob in SETS.items()
    }
    check_checkout(repo, args.expected_commit)
    destination = Path(__file__).resolve().parents[1] / "src/main/resources/rules/other"
    for name, content in outputs.items():
        (destination / f"oval-{name}-schematron-5.12.3.sch").write_bytes(content)


if __name__ == "__main__":
    try:
        main()
    except (ValueError, OSError, subprocess.CalledProcessError, etree.Error) as error:
        sys.exit(str(error))
